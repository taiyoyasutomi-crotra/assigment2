// 告知文の自動生成(F2)。運営者がコピーしてチャットに手動投稿する(半自動化)。
// 文面は顧客の募集テンプレ(2026-09-04 受領)をベースに、本システムの運用に合わせて調整:
// - 申込はログイン不要のフォーム(Googleフォームと同じくリンクを開いて入力するだけ)
// - 先着順(締切後にまとめて確定。定員を超えた分は申込順の待機)
// - 結果は当選者にメールで連絡(QRチケット添付)。申込完了時に表示される
//   確認URLからも状況を確認・キャンセルできる
// 運営者が編集して保存した場合(event.announce_text)はそちらが優先される。
import { appUrl } from "@/lib/config";
import { formatJst } from "@/lib/format";
import { type EventRow } from "@/lib/events";

export function buildAnnouncement(event: EventRow): string {
  const url = `${appUrl()}/events/${event.id}`;
  const lines = [
    `🌙✨${event.title} 開催決定✨🌙`,
    "",
    "みんなに会えるリアルイベント、やります!!",
    "",
    ...(event.description ? [event.description, ""] : []),
    `【日時】${formatJst(event.starts_at)}`,
    `【場所】${event.venue}`,
    `【定員】${event.capacity}名`,
    "【参加費】無料!🎉",
    "",
    "【申込方法】",
    "下の申込フォームから申込してね⬇️(ログイン不要・入力するだけ)",
    url,
    "",
    "【入力してもらう項目】",
    "・お名前(本名フルネーム)",
    "・サロンのニックネーム",
    "・メールアドレス",
    "",
    `【申込締切】${formatJst(event.closes_at)}`,
    "",
    "【注意事項】",
    "・サロン会員さん限定です!会員以外の方は参加できません",
    "・先着順です!定員を超えた分は申込順の繰上待ちになります",
    "・当選された方には締切後、メールでご連絡します(入場QRコード付き)",
    "・申込完了時に表示される確認ページはブックマークしてね(結果確認・キャンセルに使います)",
    "・お連れ様の同伴はできません(会員さんご本人のみ)",
    "・キャンセルする場合は確認ページから早めにお手続きしてね🙏",
    "・無断キャンセルはダメ、絶対!(繰り上げを待ってる子がいます😢)",
    "・URLの転載は本当に本当にやめてください!!",
    "",
    "当日みんなに会えるの楽しみにしてます♡",
  ];
  return lines.join("\n");
}
